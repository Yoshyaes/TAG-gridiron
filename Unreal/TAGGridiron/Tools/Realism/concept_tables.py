# Merge CallAdaptCal --concepts slices into Source/TAGGridiron/Sim/CallAdaptConcepts.inl: per concept, what it gains
# against each kind of defensive call beyond its own average over the league's defensive mix (EPA a play). Only an edge
# beyond 2 standard errors is kept (the rest 0: no evidence), then shrunk by n / (n + 150).
#   python concept_tables.py <slice files...> [--out file]
import sys, os, math
from collections import defaultdict

# the league's defensive mix (CallAdaptCal, 300 CPU games, 2026-11-25): blitz, zone blitz, man, 2-man, C3, C2, quarters, drop 8
SHARE = [11.4, 15.1, 17.2, 4.8, 26.3, 12.2, 11.2, 1.7]
args = sys.argv[1:]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Source", "TAGGridiron", "Sim", "CallAdaptConcepts.inl")
if "--out" in args:
    i = args.index("--out")
    out = args[i + 1]
    args = args[:i] + args[i + 2:]
cells = defaultdict(dict)
for f in args:
    for line in open(f, encoding="utf-8"):
        k, fam, n, s1, s2, cls = line.rstrip("\n").split("\t")
        cells[k][int(fam)] = (float(n), float(s1), float(s2))
rows, kept, total = [], 0, 0
for k in sorted(cells):
    C = cells[k]
    if len(C) < 8 or any(C[f][0] < 30 for f in range(8)):
        continue
    mean = [C[f][1] / C[f][0] for f in range(8)]
    se = [math.sqrt(max(0.0, C[f][2] / C[f][0] - mean[f] ** 2) / C[f][0]) for f in range(8)]
    avg = sum(SHARE[f] * mean[f] for f in range(8)) / sum(SHARE)
    d = []
    for f in range(8):
        e = mean[f] - avg
        total += 1
        if abs(e) > 2 * se[f]:
            kept += 1
            d.append(e * C[f][0] / (C[f][0] + 150))
        else:
            d.append(0.0)
    rows.append((k, d, int(min(C[f][0] for f in range(8)))))
with open(out, "w", encoding="utf-8", newline="\n") as fo:
    fo.write(f"// Generated by Tools/Realism/concept_tables.py from CallAdaptCal --concepts ({len(rows)} concepts, {kept} of {total} edges past 2 SE kept):\n")
    fo.write("// per concept, EPA a play against each kind of defensive call beyond its average (blitz, zone blitz, man, 2-man, C3, C2,\n// quarters, drop 8). Do not edit by hand.\n")
    fo.write("const ConceptEdge kConceptEdge[] = {\n")
    for k, d, n in rows:
        fo.write('    {"%s", {%s}},  // n >= %d\n' % (k.replace('"', '\\"'), ", ".join(f"{x:.4f}" for x in d), n))
    fo.write("};\n")
print(f"{len(rows)} concepts, {kept}/{total} edges kept -> {out}")
