"""Builds inventory-summary.md and family lists from FrostyHost's inventory.csv.

Usage
  python -I inventory_summary.py <inventory dir>
Writes inventory-summary.md and families.json next to inventory.csv.
"""
import collections
import csv
import json
import os
import re
import sys

csv.field_size_limit(sys.maxsize)

FAMILIES = [
    ("player_heads", "SkinnedMeshAsset", r"^content/characters/player/players/[^/]+/[^/]+/[^/]+_mesh$"),
    ("player_bodies", "SkinnedMeshAsset", r"^content/characters/player/bodies/[^/]+_mesh$"),
    ("helmets", "SkinnedMeshAsset", r"^content/characters/player/parts/helmets/"),
    ("footwear", "SkinnedMeshAsset", r"^content/characters/player/parts/footwear/"),
    ("armgear", "SkinnedMeshAsset", r"^content/characters/player/parts/armgear/"),
    ("torsoapparel", "SkinnedMeshAsset", r"^content/characters/player/parts/torsoapparel/"),
    ("legsapparel", "SkinnedMeshAsset", r"^content/characters/player/parts/legsapparel/"),
    ("torsogear", "SkinnedMeshAsset", r"^content/characters/player/parts/torsogear/"),
    ("sim_hair", "SkinnedMeshAsset", r"^content/characters/player/commonsimhair/"),
    ("uniform_textures", "TextureAsset", r"^content/characters/player/parts/uniforms/"),
    ("uniform_shader_presets", "AppearanceShaderPreset", r"^content/characters/player/parts/uniforms/"),
    ("skeletons", "SkeletonAsset", r"."),
    ("anim_state_assets", "AntStateAsset", r"."),
    ("coach_meshes", "SkinnedMeshAsset", r"^content/characters/coach/"),
    ("referee_meshes", "SkinnedMeshAsset", r"^content/characters/(referee|official)"),
    ("stadium_blueprints", "ObjectBlueprint", r"^content/worlds/components/stadiums/"),
    ("world_rigid_meshes", "RigidMeshAsset", r"^content/worlds/"),
]


def write(inv_dir):
    path = os.path.join(inv_dir, "inventory.csv")
    kinds = collections.Counter()
    ebx_types = collections.Counter()
    top = collections.Counter()
    res_types = collections.Counter()
    fam = {name: [] for name, _, _ in FAMILIES}
    compiled = [(n, t, re.compile(p)) for n, t, p in FAMILIES]
    banks = []
    with open(path, encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            kinds[r["kind"]] += 1
            low = r["path"].lower()
            if r["kind"] == "ebx":
                ebx_types[r["type"]] += 1
                top["/".join(low.split("/")[:2])] += 1
                for n, t, rx in compiled:
                    if r["type"] == t and rx.search(low):
                        fam[n].append({"path": r["path"], "size": int(r["size"] or 0), "superbundles": r["superbundles"]})
            elif r["kind"] == "res":
                res_types[r["type"]] += 1
                if r["type"] == "AssetBank":
                    banks.append({"path": r["path"], "size": int(r["size"] or 0), "original_size": int(r["original_size"] or 0)})
    banks.sort(key=lambda b: -b["original_size"])
    fam["anim_asset_banks"] = banks

    def suffix_counts(items):
        c = collections.Counter()
        for i in items:
            m = re.search(r"_([tmhd])_mesh$", i["path"].lower())
            c[m.group(1) if m else "-"] += 1
        return dict(c)

    lines = ["# Madden 19 inventory summary", "",
             "Generated by tools/madden/inventory_summary.py from FrostyHost inventory.csv. Private reference.", "",
             "## Totals", ""]
    lines += ["- %s %d" % (k, v) for k, v in kinds.most_common()]
    lines += ["", "## EBX by type (top 50)", "", "| Type | Count |", "| --- | --- |"]
    lines += ["| %s | %d |" % (k, v) for k, v in ebx_types.most_common(50)]
    lines += ["", "## EBX by top level path (top 40)", "", "| Path | Count |", "| --- | --- |"]
    lines += ["| %s | %d |" % (k, v) for k, v in top.most_common(40)]
    lines += ["", "## RES by type", "", "| Type | Count |", "| --- | --- |"]
    lines += ["| %s | %d |" % (k, v) for k, v in res_types.most_common()]
    lines += ["", "## Families", "",
              "Body type suffixes are `_t` thin, `_m` muscular, `_h` heavy, `_d` default (base).", ""]
    for name in list(fam):
        items = fam[name]
        lines.append("### %s (%d)" % (name, len(items)))
        if name in ("helmets", "footwear", "armgear", "torsoapparel", "legsapparel", "torsogear", "player_bodies"):
            lines.append("")
            lines.append("Body type split %s" % json.dumps(suffix_counts(items)))
        lines.append("")
        for i in items[:12]:
            extra = (" (%.1f MB raw)" % (i["original_size"] / 1e6)) if "original_size" in i else ""
            lines.append("- `%s`%s" % (i["path"], extra))
        if len(items) > 12:
            lines.append("- and %d more" % (len(items) - 12))
        lines.append("")
    with open(os.path.join(inv_dir, "inventory-summary.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    with open(os.path.join(inv_dir, "families.json"), "w", encoding="utf-8") as fh:
        json.dump(fam, fh, indent=1)
    print("summary written. families", {k: len(v) for k, v in fam.items()})


if __name__ == "__main__":
    write(sys.argv[1])
